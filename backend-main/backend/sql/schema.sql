CREATE TABLE IF NOT EXISTS nodes (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  role ENUM('industry', 'transport', 'hospital') NOT NULL,
  name VARCHAR(120) NOT NULL,
  pubkey VARCHAR(44) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_nodes_pubkey (pubkey)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS batches (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  code VARCHAR(64) NULL,
  product_name VARCHAR(160) NOT NULL,
  quantity INT UNSIGNED NOT NULL DEFAULT 0,
  unit VARCHAR(32) NOT NULL DEFAULT '',
  expires_at VARCHAR(32) NULL,
  status TINYINT UNSIGNED NOT NULL DEFAULT 0,
  on_chain TINYINT(1) NOT NULL DEFAULT 0,
  pda VARCHAR(44) NOT NULL DEFAULT '',
  bump TINYINT UNSIGNED NOT NULL DEFAULT 0,
  biotracer_pubkey VARCHAR(44) NOT NULL,
  industry_pubkey VARCHAR(44) NOT NULL,
  init_signature VARCHAR(128) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_batches_code (code),
  KEY idx_batches_status (status),
  KEY idx_batches_pda (pda)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS trace_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  batch_id INT UNSIGNED NOT NULL,
  status TINYINT UNSIGNED NOT NULL,
  action TINYINT UNSIGNED NOT NULL,
  node_pubkey VARCHAR(44) NOT NULL,
  chain_timestamp BIGINT NULL,
  tx_signature VARCHAR(128) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_trace_batch (batch_id),
  CONSTRAINT fk_trace_batch FOREIGN KEY (batch_id) REFERENCES batches (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
